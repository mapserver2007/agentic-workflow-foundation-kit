def _git_env() -> dict:
    return {
        key: value
        for key, value in os.environ.items()
        if key not in inspect_mod.SANITIZED_GIT_ENV_KEYS
        and not key.startswith(("GIT_CONFIG_KEY_", "GIT_CONFIG_VALUE_"))
    }


def git(root: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-C", os.fspath(root), *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
        env=_git_env(),
    )


def commit(root: Path) -> None:
    git(root, "add", "-A")
    subprocess.run(
        ["git", "-C", os.fspath(root), "-c", "user.name=F", "-c", "user.email=f@example.invalid", "commit", "-q", "-m", "x"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
        env=_git_env(),
    )


def make_repo(base: Path, extra: Dict[str, str] | None = None) -> Path:
    repo = base / "source"
    repo.mkdir()
    git(repo, "init", "-q")
    for name, text in {**FILES, **(extra or {})}.items():
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    commit(repo)
    git(repo, "remote", "add", "origin", "https://github.com/Owner/Repo.git")
    return repo


def complete_notes(survey_dir: Path) -> None:
    for note in sorted((survey_dir / "notes").glob("*.note.md")):
        text = note.read_text(encoding="utf-8")
        text = text.replace("reviewed: no", "reviewed: yes")
        text = re.sub(r"（責務・構造パターン[^\n]*", "対象 shard の責務と構造を読み取った。" * 20, text)
        text = text.replace(" :: card :: ", " :: full :: ")
        note.write_text(text, encoding="utf-8")


def make_quality_document(inspection: inspect_mod.RepositoryInspection, coverage_line: str, *, bodies: Dict[int, str] | None = None) -> str:
    bodies = bodies or {}
    lines = [
        "---", "status: reverse-draft", 'title: "Fixture 技術スタック統一設計書"', 'generated_at: "2026-10-31"',
        f"source_repository: {json.dumps(inspection.source_repository)}",
        f"source_ref: {json.dumps(inspection.source_ref)}",
        f"source_revision: {json.dumps(inspection.source_revision)}",
        'stack_slug: "go-fixture"', "---", "", "# 技術スタック統一設計書", "", coverage_line, "", "---", "", "## 目次", "",
    ]
    for part, bounds in validate_mod.PART_SECTIONS.items():
        lines.append(f"### Part {part}")
        for section in range(bounds[0], bounds[1] + 1):
            lines.append(f"{section}. [節題{section}](#{section}-節題{section})")
        lines.append("")
    lines.extend(["---", ""])
    for part, bounds in validate_mod.PART_SECTIONS.items():
        if part != 1:
            lines.extend(["---", ""])
        lines.extend([f"## Part {part}: 章題（{validate_mod.PART_ROLE_LABELS[part]}）", ""])
        for section in range(bounds[0], bounds[1] + 1):
            if section != bounds[0]:
                lines.extend(["---", ""])
            lines.append(f"### {section}. 節題{section}")
            if section in bodies:
                lines.extend(bodies[section].splitlines())
            elif section == 9:
                lines.extend([
                    "技術スタックの宣言値を表にまとめる。", "",
                    "| レイヤ | 技術 | バージョン方針 | 備考 |", "| --- | --- | --- | --- |",
                    "| 言語 | Go | 宣言: 1.22 | 観測: go 指令 |",
                    "| container | Alpine | 宣言: golang:1.22-alpine | build stage |",
                    "| CI | GitHub Actions | — | runner は ubuntu-latest |",
                ])
            else:
                lines.append(FILLER * 4)
            lines.append("")
    return "\n".join(lines)


class SurveyBase(unittest.TestCase):
    extra_files: Dict[str, str] | None = None

    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.base = Path(self.temp.name)
        self.repo = make_repo(self.base, self.extra_files)
        self.survey = self.base / "survey"
        survey_mod.run_survey(os.fspath(self.repo), os.fspath(self.survey))

    def tearDown(self) -> None:
        self.temp.cleanup()

    def inventory(self) -> Dict[str, dict]:
        data = json.loads((self.survey / "inventory.json").read_text(encoding="utf-8"))
        return {item["path"]: item for item in data["files"]}


class SurveyTests(SurveyBase):
    extra_files = {".env": "SECRET_TOKEN=abc123\n", "server.pem": "-----BEGIN KEY-----\n"}

    def test_classification_generated_and_exclusions(self) -> None:
        inventory = self.inventory()
        self.assertEqual(inventory["go.mod"]["cls"], "manifest")
        self.assertEqual(inventory["Dockerfile"]["cls"], "container")
        self.assertEqual(inventory[".github/workflows/ci.yml"]["cls"], "ci")
        self.assertEqual(inventory["Makefile"]["cls"], "build")
        self.assertEqual(inventory["schema/001.sql"]["cls"], "schema")
        self.assertEqual(inventory["cmd/app/main.go"]["cls"], "source")
        self.assertTrue(inventory["go.mod"]["tier1"])
        self.assertFalse(inventory["cmd/app/main.go"]["tier1"])
        self.assertEqual(inventory["gen/api.pb.go"]["generated"], "header")
        self.assertEqual(inventory[".env"]["cls"], "excluded")
        self.assertEqual(inventory["server.pem"]["cls"], "excluded")

    def test_secret_files_are_never_read_into_outputs(self) -> None:
        for path in self.survey.rglob("*"):
            if path.is_file():
                text = path.read_text(encoding="utf-8", errors="replace")
                self.assertNotIn("abc123", text, path.name)
                self.assertNotIn("BEGIN KEY", text, path.name)

    def test_facts_and_import_edges(self) -> None:
        dep = (self.survey / "facts" / "dep.md").read_text(encoding="utf-8")
        self.assertIn("go.mod#L3 | go 1.22", dep)
        self.assertIn("github.com/lib/pq v1.10.9", dep)
        entry = (self.survey / "facts" / "entry.md").read_text(encoding="utf-8")
        self.assertIn("cmd/app/main.go#L7", entry)
        imports = (self.survey / "facts" / "imports.md").read_text(encoding="utf-8")
        self.assertIn("internal/usecase → internal/domain", imports)
        sql = (self.survey / "facts" / "sql.md").read_text(encoding="utf-8")
        self.assertIn("table users cols=2", sql)
        ci = (self.survey / "facts" / "ci.md").read_text(encoding="utf-8")
        self.assertIn("job test", ci)

    def test_fixture_git_ignores_parent_repository_env(self) -> None:
        missing = os.fspath(self.base / "missing-git-dir")
        (self.repo / "another.txt").write_text("x\n", encoding="utf-8")
        with mock.patch.dict(
            os.environ,
            {"GIT_DIR": missing, "GIT_WORK_TREE": missing, "GIT_INDEX_FILE": missing},
        ):
            commit(self.repo)
            git(self.repo, "rev-parse", "HEAD")

    def test_generated_files_are_not_in_shards(self) -> None:
        shard_text = "".join(p.read_text(encoding="utf-8") for p in (self.survey / "shards").glob("*.md"))
        self.assertNotIn("gen/api.pb.go", shard_text)
        self.assertIn("cmd/app/main.go", shard_text)

    def test_output_inside_source_root_is_rejected(self) -> None:
        with self.assertRaises(survey_mod.SurveyError) as caught:
            survey_mod.run_survey(os.fspath(self.repo), os.fspath(self.repo / "out"))
        self.assertEqual(caught.exception.code, 2)

    def test_rerun_preserves_completed_notes(self) -> None:
        complete_notes(self.survey)
        survey_mod.run_survey(os.fspath(self.repo), os.fspath(self.survey))
        coverage = survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo))
        self.assertGreater(coverage.full, 0)

    def test_rerun_drops_stale_facts_and_extra_shards(self) -> None:
        complete_notes(self.survey)
        note = next((self.survey / "notes").glob("*.note.md"))
        note_text = note.read_text(encoding="utf-8")
        (self.survey / "facts" / "proto.md").write_text("# stale proto\n", encoding="utf-8")
        (self.survey / "shards" / "shard-99.md").write_text("# stale shard\n", encoding="utf-8")
        survey_mod.run_survey(os.fspath(self.repo), os.fspath(self.survey))
        self.assertFalse((self.survey / "facts" / "proto.md").exists())
        self.assertFalse((self.survey / "shards" / "shard-99.md").exists())
        self.assertTrue((self.survey / "facts" / "dep.md").is_file())
        self.assertTrue((self.survey / "facts" / "sql.md").is_file())
        self.assertTrue((self.survey / "facts" / "layout.md").is_file())
        self.assertTrue(any((self.survey / "shards").glob("shard-*.md")))
        self.assertEqual(note.read_text(encoding="utf-8"), note_text)


class CoverageCheckTests(SurveyBase):
    def note_path(self) -> Path:
        return next((self.survey / "notes").glob("*.note.md"))

    def assert_check_fails(self, fragment: str) -> None:
        with self.assertRaises(survey_mod.SurveyError) as caught:
            survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo))
        self.assertIn(fragment, str(caught.exception))

    def test_incomplete_notes_fail_and_complete_notes_pass(self) -> None:
        self.assert_check_fails("reviewed: yes ではありません")
        complete_notes(self.survey)
        coverage = survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo))
        self.assertEqual(coverage.generated, 1)
        self.assertEqual(coverage.tracked, len(FILES))
        self.assertEqual(coverage.read, coverage.full + coverage.card)
        self.assertIn("調査範囲: tracked=", coverage.line())

    def test_tier1_must_be_full(self) -> None:
        complete_notes(self.survey)
        note = self.note_path()
        text = note.read_text(encoding="utf-8").replace("- go.mod :: full ::", "- go.mod :: card ::")
        note.write_text(text, encoding="utf-8")
        self.assert_check_fails("tier1 の go.mod は full 必須")

    def test_missing_ledger_line_and_placeholder_findings_fail(self) -> None:
        complete_notes(self.survey)
        note = self.note_path()
        original = note.read_text(encoding="utf-8")
        lines = [line for line in original.splitlines() if not line.startswith("- README.md ::")]
        note.write_text("\n".join(lines) + "\n", encoding="utf-8")
        self.assert_check_fails("台帳に README.md がありません")
        note.write_text(original, encoding="utf-8")
        note.write_text(original.replace("対象 shard の責務と構造を読み取った。" * 20, "（責務・構造パターン"), encoding="utf-8")
        self.assert_check_fails("所見")

    def test_stale_digest_and_revision_fail(self) -> None:
        complete_notes(self.survey)
        note = self.note_path()
        note.write_text(re.sub(r"shard_digest: \w+", "shard_digest: 0", note.read_text(encoding="utf-8")), encoding="utf-8")
        self.assert_check_fails("shard_digest")
        complete_notes(self.survey)
        (self.repo / "NEW.md").write_text("# new\n", encoding="utf-8")
        commit(self.repo)
        with self.assertRaises(survey_mod.SurveyError) as caught:
            survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo))
        self.assertIn("source_revision", str(caught.exception))

    def test_invalid_level_is_rejected(self) -> None:
        complete_notes(self.survey)
        note = self.note_path()
        note.write_text(note.read_text(encoding="utf-8").replace("- README.md :: full ::", "- README.md :: skim ::"), encoding="utf-8")
        self.assert_check_fails("level skim が不正")


class QualityTests(SurveyBase):
    def setUp(self) -> None:
        super().setUp()
        complete_notes(self.survey)
        self.coverage_line = survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo)).line()
        self.inspection = inspect_mod.inspect_repository(os.fspath(self.repo))
        self.candidate = self.base / "candidate.md"

    def validate(self, text: str, **kwargs) -> validate_mod.ValidationResult:
        self.candidate.write_text(text, encoding="utf-8")
        options = {"source_root": os.fspath(self.repo), "survey_dir": os.fspath(self.survey)}
        options.update(kwargs)
        return validate_mod.validate_document(os.fspath(self.candidate), **options)

    def good(self, **kwargs) -> str:
        return make_quality_document(self.inspection, self.coverage_line, **kwargs)

    def assert_rejected(self, text: str, fragment: str, code: int = 1, **kwargs) -> None:
        with self.assertRaises(validate_mod.ValidationError) as caught:
            self.validate(text, **kwargs)
        self.assertIn(fragment, str(caught.exception))
        self.assertEqual(caught.exception.code, code)

    def test_valid_document_passes_with_compact_profile(self) -> None:
        result = self.validate(self.good())
        self.assertEqual(result.evidence_count, 0)

    def test_standard_profile_rejects_small_fixture(self) -> None:
        self.assert_rejected(self.good(), "分量が不足", profile="standard")

    def test_survey_dir_is_required_for_quality(self) -> None:
        self.assert_rejected(self.good(), "--survey-dir は必須", code=2, survey_dir=None)

    def test_structure_only_keeps_legacy_contract(self) -> None:
        text = self.good().replace(self.coverage_line, "")
        self.validate(text, quality=False, survey_dir=None)

    def test_coverage_line_must_be_present_and_exact(self) -> None:
        self.assert_rejected(self.good().replace(self.coverage_line, ""), "調査範囲 行がありません")
        tampered = self.coverage_line.replace("read=", "read=9")
        self.assert_rejected(self.good().replace(self.coverage_line, tampered), "調査範囲 行がありません")

    def test_evidence_token_is_rejected(self) -> None:
        tainted = self.good().replace("観測した構造", "観測した構造 evidence: go.mod#L1", 1)
        self.assert_rejected(tainted, "evidence: は書けません")

    def test_appendix_is_rejected_in_every_form(self) -> None:
        heading = self.good() + "\n---\n\n## Appendix\n\n### Appendix A: 比較\n本文\n"
        self.assert_rejected(heading, "Appendix は置けません")
        toc_link = self.good().replace("## 目次\n", "## 目次\n\n* [Appendix A: 比較](#appendix-a-比較)\n", 1)
        self.assert_rejected(toc_link, "目次に Appendix")

    def test_ledger_references_are_rejected(self) -> None:
        legacy = self.good(bodies={6: FILLER * 4 + " 根拠は [E3] にある。"})
        self.assert_rejected(legacy, "台帳参照 [E<n>]")

    def test_section_floor_and_evidence_tokens(self) -> None:
        self.assert_rejected(self.good(bodies={6: "短い。"}), "§6 の分量が不足")
        self.assert_rejected(self.good(bodies={6: FILLER * 4 + "\nevidence: go.mod#L1"}), "evidence: は書けません")

    def test_section_without_evidence_token_passes(self) -> None:
        body = FILLER * 4 + "\n[要確認]: 根拠にするファイルを特定できない"
        self.validate(self.good(bodies={6: body}))

    def test_confirmation_markers_are_capped(self) -> None:
        text = self.good(bodies={6: FILLER * 4 + "\n[要確認]: a\n[要確認]: b\n[要確認]: c"})
        self.assert_rejected(text, "[要確認] が 3 件")

    def test_confirmation_markers_in_section24_are_the_aggregation_point(self) -> None:
        aggregated = FILLER * 4 + "\n[要確認]: a\n[要確認]: b\n[要確認]: c\n[要確認]: d"
        self.validate(self.good(bodies={24: aggregated}))

    def test_not_applicable_requires_concrete_reason(self) -> None:
        self.assert_rejected(self.good(bodies={23: "該当なし: なし"}), "該当なし の根拠")
        ok = self.good(bodies={23: "該当なし: UI の dependency manifest も UI ソースも tracked に存在しないことを確認した"})
        self.validate(ok)

    def test_section9_confirmation_ratio(self) -> None:
        rows = "\n".join(
            ["表。", "", "| レイヤ | 技術 | バージョン方針 | 備考 |", "| --- | --- | --- | --- |"]
            + [f"| r{i} | t{i} | [要確認] | 備考 |" for i in range(4)]
        )
        self.assert_rejected(self.good(bodies={9: rows * 3 if False else rows + "\n" + FILLER}), "25%")

    def test_review_counts_unchanged_signature(self) -> None:
        counts = validate_mod.review_counts(self.good())
        self.assertEqual(len(counts), 4)


class AssembleTests(SurveyBase):
    def setUp(self) -> None:
        super().setUp()
        complete_notes(self.survey)
        self.coverage_line = survey_mod.check_survey(os.fspath(self.survey), os.fspath(self.repo)).line()
        self.inspection = inspect_mod.inspect_repository(os.fspath(self.repo))

    def test_assemble_generates_frontmatter_toc_and_coverage_line(self) -> None:
        full = make_quality_document(self.inspection, self.coverage_line)
        parts = self.base / "parts"
        parts.mkdir()
        (parts / "00-front.md").write_text("# 設計書\n\n* 対象: fixture\n\n{{COVERAGE}}\n", encoding="utf-8")
        (parts / "10-body.md").write_text(full[full.index("\n## Part 1:") + 1:], encoding="utf-8")
        out = self.base / "assembled.md"
        assemble_mod.assemble(
            os.fspath(parts), os.fspath(self.repo), os.fspath(self.survey), os.fspath(out),
            title="Fixture 技術スタック統一設計書", slug="go-fixture", generated_at="2026-10-31",
        )
        text = out.read_text(encoding="utf-8")
        self.assertIn(self.coverage_line, text)
        self.assertIn('generated_at: "2026-10-31"', text)
        self.assertIn("## 目次", text)
        self.assertEqual(text.count("## 目次"), 1)
        self.assertNotIn("Appendix", text)

    def test_assemble_requires_placeholder_and_rejects_invalid_body(self) -> None:
        parts = self.base / "parts2"
        parts.mkdir()
        (parts / "00-front.md").write_text("# 設計書\n", encoding="utf-8")
        (parts / "10-body.md").write_text("## Part 1: 概念編（なぜ）\n", encoding="utf-8")
        with self.assertRaises(assemble_mod.AssembleError):
            assemble_mod.assemble(
                os.fspath(parts), os.fspath(self.repo), os.fspath(self.survey),
                os.fspath(self.base / "x.md"), title="t", slug="s",
            )


