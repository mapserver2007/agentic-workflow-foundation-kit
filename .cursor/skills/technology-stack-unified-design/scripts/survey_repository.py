def _trim(text: str, limit: int = FACT_TEXT_LIMIT) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _mask_secret(name: str, value: str) -> str:
    return "<masked>" if SECRET_NAME_RE.search(name) else value


def _read_head(path: Path, limit: int) -> bytes:
    with open(path, "rb") as handle:
        return handle.read(limit)


def _ext(path: str) -> str:
    return PurePosixPath(path).suffix.lower()


def _language(path: str) -> str:
    name = PurePosixPath(path).name.lower()
    if name in ("dockerfile",) or name.startswith("dockerfile.") or name.endswith(".dockerfile"):
        return "dockerfile"
    if name in BUILD_NAMES or name.endswith(".mk"):
        return "make"
    return LANG_BY_EXT.get(_ext(path), "")


def classify_path(path: str, mode: str) -> Tuple[str, str]:
    """(cls, lang) を返す。内容に依存する判定（k8s/生成物）は別段で行う。"""
    pure = PurePosixPath(path)
    name = pure.name.lower()
    ext = _ext(path)
    if mode == "160000":
        return "submodule", ""
    if mode == "120000":
        return "symlink", ""
    if is_excluded_evidence_path(pure) or ext in BINARY_EXTENSIONS:
        return ("binary" if ext in BINARY_EXTENSIONS else "excluded"), ""
    if ext in MEDIA_EXTENSIONS:
        return "media", ""
    if name in LOCK_NAMES:
        return "lock", ""
    lang = _language(path)
    parts = pure.parts
    if name in ("dockerfile", "containerfile") or name.startswith("dockerfile.") or name.endswith(".dockerfile") or re.match(
        r"^(?:docker-)?compose[\w.\-]*\.ya?ml$", name
    ):
        return "container", lang or "dockerfile"
    if (
        (".github" in parts and "workflows" in parts)
        or name in (".gitlab-ci.yml", "jenkinsfile", "azure-pipelines.yml", "bitbucket-pipelines.yml", ".travis.yml")
        or ".circleci" in parts
    ):
        return "ci", lang
    if name in MANIFEST_NAMES or name.startswith("requirements") and ext == ".txt" or ext in (".csproj", ".sln"):
        return "manifest", lang
    if name in BUILD_NAMES or name.endswith(".mk"):
        return "build", "make"
    if ext in (".tf", ".tfvars", ".hcl"):
        return "iac", "terraform"
    if ext == ".proto" or ext in (".graphql", ".gql") or re.match(r"^(?:openapi|swagger|asyncapi)[\w.\-]*\.(?:ya?ml|json)$", name):
        return "contract", lang
    if ext in (".sql", ".prisma"):
        return "schema", lang or "prisma"
    if re.match(r"^readme(?:[._-][\w.\-]*)?$", name) or name in ("agents.md", "claude.md"):
        return "readme", ""
    if lang in SOURCE_LANGS:
        return ("test" if TEST_PATH_RE.search(path) else "source"), lang
    if ext in DOC_EXTENSIONS:
        return "doc", ""
    if ext in TEMPLATE_EXTENSIONS:
        return "template", ""
    if ext in CONFIG_EXTENSIONS or name.startswith("."):
        return "config", ""
    return "config", ""


def generated_reason(path: str, head_lines: Sequence[str]) -> str:
    for line in head_lines[:15]:
        if GENERATED_HEADER_RE.search(line):
            return "header"
    if GENERATED_FILENAME_RE.search(path):
        return "filename"
    parts = PurePosixPath(path).parts[:-1]
    if any(part in GENERATED_DIR_NAMES for part in parts):
        return "path"
    return ""


