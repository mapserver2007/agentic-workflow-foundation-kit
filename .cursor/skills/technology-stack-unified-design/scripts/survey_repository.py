def _git_entries(source_root: Path) -> List[Tuple[str, str]]:
    result = _safe_git(source_root, ["ls-files", "-s", "-z"], git_executable="git", env=None)
    entries: List[Tuple[str, str]] = []
    for item in result.stdout.split(b"\0"):
        if not item:
            continue
        meta, _, raw_path = item.partition(b"\t")
        mode = meta.split(b" ", 1)[0].decode("ascii", errors="replace")
        entries.append((raw_path.decode("utf-8", errors="surrogateescape"), mode))
    entries.sort(key=lambda entry: entry[0])
    return entries


def scan_repository(source_root: Path) -> SurveyState:
    state = SurveyState()
    entries = _git_entries(source_root)
    # go.mod を先に読んで module 解決表を作る（import 解像度のため）。
    for path, mode in entries:
        if PurePosixPath(path).name == "go.mod" and mode == "100644":
            text = _decode(_read_head(source_root / path, MAX_READ_BYTES))
            match = re.search(r"(?m)^module\s+(\S+)", text)
            if match:
                directory = str(PurePosixPath(path).parent)
                state.go_modules[match.group(1)] = "" if directory == "." else directory
    for path, mode in entries:
        cls, lang = classify_path(path, mode)
        rec = FileRecord(path=path, size=0, lines=0, cls=cls, lang=lang)
        state.records.append(rec)
        if cls in NON_READABLE_CLASSES:
            if cls in ("lock", "media"):
                try:
                    rec.size = os.lstat(source_root / path).st_size
                except OSError:
                    pass
            continue
        full = source_root / path
        try:
            metadata = os.lstat(full)
        except OSError:
            rec.cls = "excluded"
            continue
        if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode):
            rec.cls = "symlink"
            continue
        rec.size = metadata.st_size
        head = _read_head(full, MAX_READ_BYTES)
        if b"\0" in head[:8192]:
            rec.cls = "binary"
            continue
        if metadata.st_size > MAX_READ_BYTES:
            rec.oversize = True
            rec.lines = _count_lines(full) if metadata.st_size <= MAX_COUNT_BYTES else -1
        else:
            rec.lines = head.count(b"\n") + (0 if head.endswith(b"\n") or not head else 1)
        text = _decode(head)
        head_lines = text.split("\n", 16)[:16]
        if rec.cls in ("source", "test", "config", "contract", "template", "schema", "doc") and MINIFIED_LINE_RE.search(text):
            rec.generated = "minified"
            _register_generated(state, rec, head_lines)
            continue
        if rec.cls in ("source", "test", "config", "contract", "template", "schema", "doc"):
            reason = generated_reason(path, head_lines)
            if reason:
                rec.generated = reason
                _register_generated(state, rec, head_lines)
                continue
        rec.tier1 = rec.cls in TIER1_CLASSES and not rec.oversize
        rec.card = _trim(scan_file(state, rec, text), CARD_LIMIT)
    _resolve_imports(state)
    if state.tool_files == []:
        state.tool_files = _tooling_files(state.records)
    return state


def _count_lines(path: Path) -> int:
    count = 0
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            count += chunk.count(b"\n")
    return count


def _register_generated(state: SurveyState, rec: FileRecord, head_lines: Sequence[str]) -> None:
    directory = str(PurePosixPath(rec.path).parent)
    parts = directory.split("/")
    group = "/".join(parts[:3]) if directory != "." else "(root)"
    tool = ""
    header_line = 0
    header_text = ""
    for index, line in enumerate(head_lines, start=1):
        if GENERATED_HEADER_RE.search(line):
            header_line, header_text = index, line.strip()
            match = GENERATOR_TOOL_RE.search(line)
            if match:
                tool = next(value for value in match.groups() if value)
            break
    if not tool:
        for suffix, hint in GENERATOR_FILENAME_HINTS:
            if rec.path.endswith(suffix):
                tool = hint
                break
    if not tool and header_line:
        match = GENERATOR_TOOL_RE.search("\n".join(head_lines))
        if match:
            tool = next(value for value in match.groups() if value)
    tool = tool.rstrip(".,;:")
    key = (group, tool or rec.generated)
    entry = state.generated_groups.get(key)
    if entry is None:
        state.generated_groups[key] = [0, rec.path, header_line, header_text, rec.generated]
        entry = state.generated_groups[key]
    entry[0] += 1


def _tooling_files(records: Sequence[FileRecord]) -> List[Tuple[str, str]]:
    found = []
    for rec in records:
        name = PurePosixPath(rec.path).name.lower()
        if name in TOOLING_NAMES and rec.cls not in NON_READABLE_CLASSES:
            found.append((rec.path, rec.cls))
    return found


def _resolve_imports(state: SurveyState) -> None:
    source_dirs: Set[str] = set()
    for rec in state.records:
        if rec.cls in ("source", "test") and not rec.generated:
            source_dirs.add(str(PurePosixPath(rec.path).parent))
    dirs_with_prefix: Set[str] = set()
    for directory in source_dirs:
        parts = directory.split("/")
        for i in range(1, len(parts) + 1):
            dirs_with_prefix.add("/".join(parts[:i]))
    for path, kind, origin, targets in state.pending_imports:
        source_dir = origin if kind != "jvm" else str(PurePosixPath(path).parent)
        for target in targets:
            resolved = _resolve_target(state, kind, path, target, dirs_with_prefix)
            if resolved is not None and resolved != source_dir:
                state.edges[(source_dir, resolved)] += 1


def _resolve_target(state: SurveyState, kind: str, path: str, target: str, known_dirs: Set[str]) -> Optional[str]:
    if kind == "go":
        return target if target in known_dirs or target == "." else None
    if kind == "js":
        candidate = target
        while candidate and candidate not in known_dirs and candidate != ".":
            candidate = str(PurePosixPath(candidate).parent)
            if candidate == ".":
                break
        return candidate if candidate in known_dirs else None
    if kind == "python":
        if target.startswith("."):
            dots = len(target) - len(target.lstrip("."))
            base = PurePosixPath(path).parent
            for _ in range(max(dots - 2, 0)):
                base = base.parent
            rel = target.lstrip(".").replace(".", "/")
            candidate = str(base / rel) if rel else str(base)
        else:
            candidate = target.replace(".", "/")
        while candidate and candidate not in known_dirs and "/" in candidate:
            candidate = candidate.rsplit("/", 1)[0]
        return candidate if candidate in known_dirs else None
    if kind == "jvm":
        package = target.rsplit(".", 1)[0] if not target.endswith(".*") else target[:-2]
        while package:
            if package in state.pkg_to_dir:
                return state.pkg_to_dir[package]
            if "." not in package:
                break
            package = package.rsplit(".", 1)[0]
    return None


