NOTE_LINE_RE = re.compile(r"^- (?P<path>.+?) :: (?P<level>[a-z]+) :: ")


@dataclass
class Coverage:
    tracked: int
    skipped: int
    generated: int
    read: int
    full: int
    card: int
    shards: int
    revision: str

    def line(self) -> str:
        return (
            f"調査範囲: tracked={self.tracked}; skipped={self.skipped}; generated={self.generated}; "
            f"read={self.read} (full={self.full}, card={self.card}); shards={self.shards}; revision={self.revision[:7]}"
        )


def _parse_note(path: Path) -> Tuple[Dict[str, str], str, Dict[str, str]]:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    meta: Dict[str, str] = {}
    body_start = 0
    if lines and lines[0] == "---":
        for index in range(1, len(lines)):
            if lines[index] == "---":
                body_start = index + 1
                break
            key, _, value = lines[index].partition(":")
            meta[key.strip()] = value.strip()
    findings = ""
    in_findings = False
    levels: Dict[str, str] = {}
    for line in lines[body_start:]:
        if line.startswith("## "):
            in_findings = line.strip() == "## 所見"
            continue
        if in_findings:
            findings += line + "\n"
        match = NOTE_LINE_RE.match(line)
        if match:
            levels[match.group("path")] = match.group("level")
    return meta, findings.strip(), levels


def check_survey(survey_dir: str, source_root: Optional[str] = None) -> Coverage:
    directory = Path(survey_dir)
    inventory_path = directory / "inventory.json"
    try:
        inventory = json.loads(inventory_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SurveyError("survey の inventory.json を読み取れません（survey を先に実行してください）", 2) from exc
    revision = inventory.get("source_revision", "")
    if source_root is not None:
        try:
            current = inspect_repository(source_root).source_revision
        except InspectionError as exc:
            raise SurveyError(str(exc), exc.code) from exc
        if current != revision:
            raise SurveyError("survey の source_revision が現在の worktree と一致しません（survey を再実行してください）")
    files = inventory["files"]
    shards = int(inventory["shards"])
    problems: List[str] = []
    expected: Dict[int, Dict[str, dict]] = defaultdict(dict)
    skipped = generated = 0
    for item in files:
        if item["generated"]:
            generated += 1
        elif item["cls"] in NON_READABLE_CLASSES:
            skipped += 1
        else:
            expected[int(item["shard"])][item["path"]] = item
    full = card = 0
    for shard in range(shards):
        note_path = directory / "notes" / f"shard-{shard:02d}.note.md"
        if not note_path.is_file():
            problems.append(f"shard-{shard:02d}: note がありません")
            continue
        meta, findings, levels = _parse_note(note_path)
        if meta.get("shard_digest") != inventory["shard_digests"].get(str(shard)):
            problems.append(f"shard-{shard:02d}: note の shard_digest が現在の survey と一致しません（survey 再実行後は note を作り直してください）")
        if meta.get("reviewed") != "yes":
            problems.append(f"shard-{shard:02d}: reviewed: yes ではありません")
        if len(findings) < MIN_FINDING_CHARS or findings.startswith("（責務・構造パターン"):
            problems.append(f"shard-{shard:02d}: 所見が {MIN_FINDING_CHARS} 文字未満、または雛形のままです")
        want = expected.get(shard, {})
        for path, item in want.items():
            level = levels.get(path)
            if level is None:
                problems.append(f"shard-{shard:02d}: 台帳に {path} がありません")
            elif level not in LEVELS:
                problems.append(f"shard-{shard:02d}: {path} の level {level} が不正です")
            elif item["tier1"] and level != "full":
                problems.append(f"shard-{shard:02d}: tier1 の {path} は full 必須です")
            elif level == "full":
                full += 1
            else:
                card += 1
        for path in levels:
            if path not in want:
                problems.append(f"shard-{shard:02d}: 台帳に shard 外の {path} があります")
    if problems:
        shown = "\n  ".join(problems[:30])
        more = f"\n  …ほか {len(problems) - 30} 件" if len(problems) > 30 else ""
        raise SurveyError(f"全量読解の台帳が不完全です（{len(problems)} 件）:\n  {shown}{more}")
    return Coverage(
        tracked=len(files), skipped=skipped, generated=generated, read=full + card,
        full=full, card=card, shards=shards, revision=revision,
    )


def load_inventory_stats(survey_dir: str) -> Dict[str, int]:
    inventory = json.loads((Path(survey_dir) / "inventory.json").read_text(encoding="utf-8"))
    readable = sum(1 for item in inventory["files"] if not item["generated"] and item["cls"] not in NON_READABLE_CLASSES)
    return {"tracked": len(inventory["files"]), "readable": readable, "shards": int(inventory["shards"])}


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    survey = sub.add_parser("survey")
    survey.add_argument("--source-root", required=True)
    survey.add_argument("--out-dir", default="tmp/tech-stack-survey")
    survey.add_argument("--shard-files", type=int, default=DEFAULT_SHARD_FILES)
    survey.add_argument("--shard-bytes", type=int, default=DEFAULT_SHARD_BYTES)
    check = sub.add_parser("check")
    check.add_argument("--survey-dir", default="tmp/tech-stack-survey")
    check.add_argument("--source-root")
    args = parser.parse_args(argv)
    try:
        if args.command == "survey":
            summary = run_survey(args.source_root, args.out_dir, args.shard_files, args.shard_bytes)
            print(
                f"[survey_repository] PASS: tracked={summary['tracked']} readable={summary['readable']} "
                f"shards={summary['shards']} out={args.out_dir}"
            )
            return 0
        coverage = check_survey(args.survey_dir, args.source_root)
    except (SurveyError, InspectionError) as exc:
        print(f"[survey_repository] ERROR: {exc}", file=sys.stderr)
        return exc.code
    print(f"[survey_repository] PASS: {coverage.line()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
