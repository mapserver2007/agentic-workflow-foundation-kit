def _is_std_go(path: str) -> bool:
    return "." not in path.split("/", 1)[0]


def _go_ext_key(path: str) -> str:
    parts = path.split("/")
    host = parts[0]
    if host in GO_SPECIAL_CLOUD and len(parts) >= 3:
        if host == "cloud.google.com" and parts[1] != "go":
            return "/".join(parts[:2])
        return "/".join(parts[:3])
    return "/".join(parts[:2])


