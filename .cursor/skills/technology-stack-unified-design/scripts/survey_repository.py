    out.append("| ディレクトリ | 件数 | 生成器/判定 | 例 |")
    out.append("| --- | --- | --- | --- |")
    ordered = sorted(state.generated_groups.items(), key=lambda kv: -kv[1][0])
    for (group, tool), (count, sample, header_line, header_text, reason) in ordered[:25]:
        example = f"{sample}#L{header_line} {_trim(header_text, 80)}" if header_line else sample
        out.append(f"| {group} | {count} | {tool} ({reason}) | {example} |")
    out.append("")
    out.append("## 実行入口（entry）")
    out.extend(f"- {line}" for line in _fact_lines(state, "entry", 40))
    out.append("")
    out.append("## compose service")
    out.extend(f"- {line}" for line in _fact_lines(state, "compose") if "service " in line)
