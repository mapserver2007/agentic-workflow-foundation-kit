    ranked = sorted(keys, key=lambda k: -(len(state.ext_imports.get(k, {})) + len(state.ext_test_imports.get(k, {}))))
    for key in ranked[:60]:
        out.append(f"| {key} | {len(state.ext_imports.get(key, {}))} | {len(state.ext_test_imports.get(key, {}))} |")
    out.append("")
    out.append("## proto service / rpc 数（ファイル別）")
    proto_counts: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    for path, _line, _text, note in state.facts.get("proto", []):
        if note == "service":
            proto_counts[str(PurePosixPath(path).parent)][0] += 1
        elif note == "rpc":
            proto_counts[str(PurePosixPath(path).parent)][1] += 1
    for directory, (services, rpcs) in sorted(proto_counts.items()):
        out.append(f"- {directory}: services={services} rpcs={rpcs}")
    out.append("")
    out.append("## SQL table")
    tables = [f"{p}#L{l} | {t}" for p, l, t, n in state.facts.get("sql", []) if n.startswith("table ")]
    out.append(f"- tables={len(tables)}（詳細は facts/sql.md）")
